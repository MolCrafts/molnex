"""Write ``contraction_tables.hpp``: the merged symmetric-contraction term tables of MACE's family.

One table per ``(l_in, l_out, degree)`` — node irreps ``U×0e+…+U×l_in``,
output irreps ``U×0e+…+U×l_out`` (natural parity, ``l_out ≤ l_in ≤ 3``), body
orders ``1..degree`` with ``degree ∈ {2, 3}`` — read off cuEquivariance's
descriptor through :class:`molrep.equivariance.symmetric_contraction_terms.SymmetricContractionTerms`
(permuted monomials merged, slots ascending, sorted by output segment, then
``i, j, k, w``). The kernels unroll a table at compile time and take the
coefficient *values* at run time; the Python module checks the table it reads
off its own descriptor against the compiled one before it selects the compiled
kernel. Run from the repository root:

    python csrc/equivariance/generate_contraction_tables.py > csrc/equivariance/contraction_tables.hpp
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

import molrep.eq as meq  # noqa: E402
from molrep.equivariance.descriptor import natural_irreps  # noqa: E402
from molrep.equivariance.symmetric_contraction_terms import (  # noqa: E402
    SymmetricContractionTerms,
)

L_MAX = 3
DEGREES = (2, 3)
CONFIGS = [
    (l_in, l_out, degree)
    for l_in in range(1, L_MAX + 1)
    for l_out in range(0, l_in + 1)
    for degree in DEGREES
]


def main() -> None:
    out = sys.stdout
    out.write(
        "// Generated by generate_contraction_tables.py — do not edit. The merged term\n"
        "// tables of MACE's symmetric contractions (natural parity, l_out <= l_in <= 3,\n"
        "// degrees 2 and 3): columns w, i, j, k, o; a missing slot is the sentinel S.\n"
        "#pragma once\n\n#include <array>\n#include <cstdint>\n\n"
        "namespace molnex::equivariance::sc {\n\n"
        "struct Term {\n  int16_t w, i, j, k, o;\n};\n\n"
        "template <int LIN, int LOUT, int DEG>\nstruct Table;\n\n"
    )
    out.write("#define MOLNEX_SC_CONFIGS(X) \\\n")
    out.write("  " + " ".join(f"X({a}, {b}, {c})" for a, b, c in CONFIGS) + "\n\n")
    for l_in, l_out, degree in CONFIGS:
        tables = SymmetricContractionTerms(natural_irreps(4, l_in), natural_irreps(4, l_out), degree)
        s = tables.input_segments
        rows = []
        for w, i, j, k, o in tables.terms.tolist():
            rows.append((w, i, j if j >= 0 else s, k if k >= 0 else s, o))
        out.write(
            f"template <>\nstruct Table<{l_in}, {l_out}, {degree}> {{\n"
            f"  static constexpr int NS = {s}, NB = {tables.weight_segments}, "
            f"NO = {tables.output_segments}, NT = {len(rows)};\n"
            f"  static constexpr std::array<Term, NT> terms = {{{{\n"
        )
        for start in range(0, len(rows), 6):
            out.write("    " + " ".join(f"{{{w}, {i}, {j}, {k}, {o}}}," for w, i, j, k, o in rows[start : start + 6]) + "\n")
        out.write("  }};\n};\n\n")
    out.write("}  // namespace molnex::equivariance::sc\n")


if __name__ == "__main__":
    main()
