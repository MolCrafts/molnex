"""Write ``contracter_tables.hpp``: the term tables of every tensor product an Allegro model builds.

:meth:`molzoo.allegro.encoder.AllegroEncoder._layer_irreps` prunes the tensor
track per layer; over ``l_max ∈ {1, 2, 3}``, both parities and up to five
layers that is 21 distinct ``(irreps_in1, irreps_in2, irreps_out)`` triples.
Each table is the flattened ``u,iu,ju,ku+ijk`` polynomial read off the
descriptor through :class:`molrep.equivariance.contracter_terms.ContracterTerms`
(columns ``w, i, j, o`` in path order). The kernels unroll a table at compile
time and take the coefficient *values* at run time; the Python module compares
the table it reads off its own descriptor with the compiled ones before it
selects a compiled kernel. Run from the repository root:

    python csrc/equivariance/generate_contracter_tables.py > csrc/equivariance/contracter_tables.hpp
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

import molrep.eq as meq  # noqa: E402
from molrep.equivariance.contracter_terms import ContracterTerms  # noqa: E402
from molrep.interaction.product import sh_irreps_from_l_max  # noqa: E402
from molzoo.allegro.encoder import AllegroEncoder  # noqa: E402
from molzoo.allegro.spec import AllegroSpec  # noqa: E402

MAX_LAYERS = 5


def triples() -> list[tuple[str, str, str]]:
    found: dict[tuple[str, str, str], None] = {}
    for l_max in (1, 2, 3):
        for parity in (False, True):
            for num_layers in range(1, MAX_LAYERS + 1):
                spec = AllegroSpec(
                    atomic_numbers=[1, 6],
                    r_max=4.0,
                    l_max=l_max,
                    parity=parity,
                    num_layers=num_layers,
                    num_scalar_features=8,
                    num_tensor_features=4,
                )
                schedule = AllegroEncoder._layer_irreps(spec)
                sh = str(meq.Irreps("O3", sh_irreps_from_l_max(l_max)))
                for a, b in zip(schedule, schedule[1:], strict=False):
                    found.setdefault((str(a), sh, str(b)), None)
    return sorted(found, key=lambda key: (len(key[0]), key))


def main() -> None:
    out = sys.stdout
    keys = triples()
    out.write(
        "// Generated by generate_contracter_tables.py — do not edit. The term tables of\n"
        "// the tensor products Allegro builds (l_max <= 3, both parities, up to five\n"
        "// layers): columns w, i, j, o in path order.\n"
        "#pragma once\n\n#include <array>\n#include <cstdint>\n\n"
        "namespace molnex::equivariance::ct {\n\n"
        "struct Term {\n  int16_t w, i, j, o;\n};\n\n"
        "template <int ID>\nstruct Table;\n\n"
        f"constexpr int kConfigs = {len(keys)};\n\n"
    )
    out.write("#define MOLNEX_CT_CONFIGS(X) \\\n  " + " ".join(f"X({n})" for n in range(len(keys))) + "\n\n")
    for n, (a, s, b) in enumerate(keys):
        tables = ContracterTerms(meq.Irreps("O3", a), meq.Irreps("O3", s), meq.Irreps("O3", b), 4)
        rows = tables.terms.tolist()
        out.write(
            f"// {a} x {s} -> {b}\ntemplate <>\nstruct Table<{n}> {{\n"
            f"  static constexpr int NS1 = {tables.input1_segments}, NS2 = {tables.input2_segments}, "
            f"NB = {tables.weight_segments}, NO = {tables.output_segments}, NT = {len(rows)};\n"
            f"  static constexpr std::array<Term, NT> terms = {{{{\n"
        )
        for start in range(0, len(rows), 8):
            out.write("    " + " ".join(f"{{{w}, {i}, {j}, {o}}}," for w, i, j, o in rows[start : start + 8]) + "\n")
        out.write("  }};\n};\n\n")
    out.write("}  // namespace molnex::equivariance::ct\n")


if __name__ == "__main__":
    main()
